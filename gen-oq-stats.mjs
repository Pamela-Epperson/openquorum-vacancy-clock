#!/usr/bin/env node
// gen-oq-stats.mjs — derive the live OpenQuorum numbers from states.config.js
// and emit oq-stats.json. Run this in the vacancy-clock pipeline (see WIRING.md)
// so the primer's numbers update themselves as enrichment + Suggest-a-Board grow the count.
//
// Usage:  node gen-oq-stats.mjs [path/to/states.config.js] [path/to/out/oq-stats.json]
// Defaults: ./src/states.config.js  ->  ./oq-stats.json
//
// NOTE: counts are derived by PARSING the actual STATE_CONFIG object, not by
// regex-scanning the file text. This deliberately ignores the schema-example
// rows inside the top-of-file comment block (e.g. `// totalSeats: 15`), which a
// naive text scan would wrongly count — the bug that made published totals read
// high (449/5,137) vs the true data (447/5,122).

import { readFileSync, writeFileSync } from "node:fs";

const inPath  = process.argv[2] || "src/states.config.js";
const outPath = process.argv[3] || "oq-stats.json";

const src = readFileSync(inPath, "utf8");

// Evaluate the module in isolation to recover the real STATE_CONFIG object.
// Strip ESM import/export syntax so it runs inside a plain Function.
function loadConfig(text) {
  const stripped = text
    .replace(/^\s*import[^\n]*$/gm, "")
    .replace(/export\s+default\s+/g, "")
    .replace(/export\s+const\s+/g, "const ")
    .replace(/export\s+let\s+/g, "let ")
    .replace(/export\s+var\s+/g, "var ")
    .replace(/export\s+function/g, "function")
    .replace(/export\s*\{[^}]*\}\s*;?/g, "");
  // eslint-disable-next-line no-new-func
  return (new Function(stripped + "\n;return STATE_CONFIG;"))();
}

let cfg;
try {
  cfg = loadConfig(src);
} catch (err) {
  console.error(`gen-oq-stats: could not parse STATE_CONFIG from ${inPath}: ${err.message}`);
  process.exit(1);
}

const codes = Object.keys(cfg);
const jurisdictions = codes.length;
const hasDC = codes.includes("DC");

let boards = 0, seats = 0, vacancies = 0;
for (const code of codes) {
  const rows = (cfg[code] && cfg[code].boards) || [];
  for (const b of rows) {
    if (Number.isInteger(b.totalSeats) && b.totalSeats > 0) {
      boards += 1;
      seats += b.totalSeats;
      vacancies += Number.isInteger(b.vacantSeats) ? b.vacantSeats : 0;
    }
  }
}

const out = {
  jurisdictions,
  states: jurisdictions - (hasDC ? 1 : 0),
  dc: hasDC,
  boards,
  seats,
  vacancies, // floor: inventory-mode states report 0 current vacancies by design
  updatedAt: new Date().toISOString().slice(0, 10),
  source: `${inPath} (generated by gen-oq-stats.mjs)`,
  note: "Auto-generated from states.config.js and pushed to each site root by the oq-stats-sync workflow on every config change. Do not hand-edit."
};

writeFileSync(outPath, JSON.stringify(out, null, 2) + "\n");
console.log(`oq-stats.json written: ${jurisdictions} jurisdictions · ${boards} boards · ${seats} seats · ${vacancies} vacancies`);
