#!/usr/bin/env node
// gen-pnp-gaps.mjs — turn the Passed-Not-Paid source of truth into pnp-gaps.json,
// the data file the gallery fetches at openquorum.us.com/pnp-gaps.json.
//
// Usage:  node gen-pnp-gaps.mjs [path/to/passed-not-paid.config.js] [path/to/out/pnp-gaps.json]
// Defaults: ./src/passed-not-paid.config.js  ->  ./pnp-gaps.json
//
// It runs the SAME prove-it contract the CLI validator runs (imported from
// src/passed-not-paid.tools.mjs) and REFUSES to emit if any case fails — so a
// bad edit can never reach the site, whether the workflow or a human runs it.
// Output records are the gallery's view-model (barPct, fundedLabel, gapLabel,
// note, sources, + closedLabel/wasLabel for resolved cases).

import { readFileSync, writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";
import { resolve } from "node:path";
import { validate } from "./src/passed-not-paid.tools.mjs";

const inPath  = process.argv[2] || "src/passed-not-paid.config.js";
const outPath = process.argv[3] || "pnp-gaps.json";

// Load the source of truth from the given path.
const mod = await import(pathToFileURL(resolve(inPath)).href);
const GAPS = mod.GAPS || mod.default;
if (!Array.isArray(GAPS)) {
  console.error(`gen-pnp-gaps: could not read GAPS array from ${inPath}`);
  process.exit(1);
}

// Prove-it gate: nothing ships unvalidated.
const errors = validate(GAPS);
if (errors.length) {
  console.error(`gen-pnp-gaps: REFUSING to emit — ${errors.length} contract error(s):`);
  for (const e of errors) console.error(`  - ${e}`);
  process.exit(1);
}

// Map each source record to the gallery view-model (field names the gallery renders).
const view = GAPS.map(g => ({
  id: g.id,
  tier: g.tier,
  status: g.status,
  domain: g.domain,
  barPct: g.barPct,
  title: g.title,
  law: g.law,
  authorized: g.authorized,
  appropriated: g.appropriated,
  fundedLabel: g.fundedShare,
  gapLabel: g.gap,
  constituent: g.constituent,
  note: g.criticalNote,
  sources: g.sources,
  ...(g.status === "resolved" ? { closedLabel: g.closedLabel, wasLabel: g.wasLabel } : {})
}));

const out = {
  generatedAt: new Date().toISOString().slice(0, 10),
  source: `${inPath} (generated by gen-pnp-gaps.mjs)`,
  note: "Auto-generated from passed-not-paid.config.js and pushed to the site root by the pnp-sync workflow on every change. Do not hand-edit.",
  count: view.length,
  byTier: {
    crumbs: view.filter(g => g.tier === "crumbs").length,
    shortfall: view.filter(g => g.tier === "shortfall").length
  },
  gaps: view
};

writeFileSync(outPath, JSON.stringify(out, null, 2) + "\n");
console.log(`pnp-gaps.json written: ${view.length} cases · ${out.byTier.crumbs} crumbs · ${out.byTier.shortfall} shortfall`);
